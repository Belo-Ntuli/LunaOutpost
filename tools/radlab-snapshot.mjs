// Downloads real space-weather data and writes a bundled snapshot (src/data/radlabSnapshot.js) used when
// the live APIs can't be reached (offline / static hosting):
//   - NASA RadLab: daily Moon radiation measured by CRaTER on the Lunar Reconnaissance Orbiter
//   - NASA DONKI:  the solar flare / particle event that caused each storm
// Usage: npm run radlab:snapshot
import { writeFileSync } from 'node:fs';
import { RADIATION_WINDOWS, radlabUrl } from '../src/data/radlabWindows.js';
import { dailyMeans, makeRadiation } from '../src/game/radiation.js';
import { fetchStormCauses } from '../src/api/donki.js';

const API = 'https://visualization.osdr.nasa.gov/radlab/api/';
const windows = [];
for (const w of RADIATION_WINDOWS) {
  const url = API + radlabUrl(w.start);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  const daily = dailyMeans(await res.json(), w.start);
  const storms = await fetchStormCauses(makeRadiation({ ...w, daily, source: 'snapshot' }));
  console.log(w.start, w.label, `${daily.filter((x) => x === null).length} missing days,`, 'storms:', storms.map((s) => `${s.date} ${s.flare ?? 'no flare'} (${s.strength})`).join(', '));
  windows.push({ ...w, daily, storms });
}

const file = `// Generated by tools/radlab-snapshot.mjs - do not edit by hand.
// daily:  mean absorbed dose rate (μGy/hour) measured by CRaTER-D1D2 on the Lunar Reconnaissance Orbiter.
//         Source: NASA RadLab, https://visualization.osdr.nasa.gov/radlab/
// storms: storm onsets matched to solar flares / particle events.
//         Source: NASA DONKI, https://ccmc.gsfc.nasa.gov/tools/DONKI/
// Retrieved ${new Date().toISOString().slice(0, 10)}.
export const RADLAB_SNAPSHOT = ${JSON.stringify(windows, null, 2)};
`;
writeFileSync(new URL('../src/data/radlabSnapshot.js', import.meta.url), file);
console.log(`Wrote ${windows.length} windows to src/data/radlabSnapshot.js`);
